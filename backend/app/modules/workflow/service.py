"""Workflow & Dependencies service.

Same module pipeline shape as the rest. Workflow synthesises the upstream
analyses (visa, documents, family, finance, job-fit, country-comparison)
into a directed task graph. The graph is generated by the LLM but the
service performs structural validation in a post-AI step:

  - Every edge endpoint must reference a declared node id.
  - The current_stage_node_id must reference a declared node id.
  - Every entry in critical_path must reference a declared node id.
  - blocked_node_ids must match status="blocked" nodes (we only enforce a
    subset relationship to give the model some headroom).
  - The graph must be a DAG (no cycles).

If structural validation fails we treat it the same as schema validation
failure — surface a failed envelope so the frontend can render the failed
state cleanly.
"""

